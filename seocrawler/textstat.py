TOP_N, TOP_MIN = 5, 3   # академическая тошнота: до 5 самых частых слов, которые повторяются хотя бы 3 раза


def words_of(text):
    return [w.lower().replace("ё", "е") for w in WORD.findall(text or "")]


def stats(text, min_words=0):
    """{"words", "water" (%), "classic", "academic" (%), "top": [(слово, повторов)], "water_words": [...]}
    или None, если слов меньше min_words."""
    ws = words_of(text)
    n = len(ws)
    if not n or n < min_words:
        return None
    water_set = {w.replace("ё", "е") for w in WATER}
    service_set = {w.replace("ё", "е") for w in SERVICE}
    water = [w for w in ws if w in water_set]
    counts, forms = Counter(), {}
    for w in ws:
        if w in water_set or w in service_set or len(w) < 3:
            continue
        k = stem(w) if re.match(r"[а-я]", w) else w
        counts[k] += 1
        forms.setdefault(k, Counter())[w] += 1
    top = counts.most_common(TOP_N)
    acad = sum(c for _, c in top if c >= TOP_MIN)
    return {
        "words": n,
        "water": round(100 * len(water) / n, 1),
        "classic": round(math.sqrt(top[0][1]), 1) if top else 0.0,
        "academic": round(100 * acad / n, 1),
        "top": [(forms[k].most_common(1)[0][0], c) for k, c in top[:3]],
        "water_words": [w for w, _ in Counter(water).most_common(5)],
    }


def fmt(x):
    """7.0 → «7», 7.25 → «7,3»."""
    if x is None:
        return ""
    x = round(float(x), 1)
    return str(int(x)) if x == int(x) else str(x).replace(".", ",")


def top_text(st, k=3):
    """«котел - 24, газовый - 15»."""
    return ", ".join(f"{w} - {c}" for w, c in (st or {}).get("top", [])[:k])
