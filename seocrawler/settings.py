# ---------- Изменения из окна программы: файл «настройки.json» в папке «данные».
# Автотесты его не читают (переменная CLAYLER_NO_USER_SETTINGS=1), чтобы эталоны не зависели от настроек.
import json as _json
import os as _os
from . import jsonfile as _jsonfile

DEFAULTS = {k: v for k, v in dict(globals()).items() if k.isupper() and k not in ("UI",)}
from .paths import data as _data  # noqa: E402
USER_FILE = _data("настройки.json")


def load_user():
    """Изменения пользователя: {имя: значение} — только известные имена и подходящего типа."""
    if _os.environ.get("CLAYLER_NO_USER_SETTINGS") == "1":
        return {}
    try:
        with open(USER_FILE, encoding="utf-8") as f:
            data = _json.load(f)
    except (OSError, ValueError):
        return {}
    out = {}
    for k, v in data.items():
        d = DEFAULTS.get(k)
        if d is None:
            continue
        try:
            if isinstance(d, list):
                out[k] = [str(x) for x in v]
            elif isinstance(d, (int, float)) and (float(v) > 0 or (k in ZERO_OK and float(v) == 0)):
                out[k] = type(d)(float(v)) if isinstance(d, float) else int(float(v))
        except (TypeError, ValueError):
            pass
    return out


def save_user(data):
    """Записывает только то, что отличается от значений по умолчанию."""
    diff = {k: v for k, v in data.items() if k in DEFAULTS and v != DEFAULTS[k]}
    _jsonfile.save(USER_FILE, diff, indent=1)


globals().update(load_user())
