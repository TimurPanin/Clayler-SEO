def client_text(s):
    """Фразы оператору → для клиента: тот же REPLACE, что у отчёта для клиента (для PDF, Word и Excel)."""
    if not isinstance(s, str):
        return s
    for a, b in REPLACE:
        if a in s:
            s = s.replace(a, b)
    return s


def leftovers(doc):
    """Служебные слова, оставшиеся в тексте (для проверки): «программ…», «.csv», «Обновить отчёт», чужие программы."""
    # таблицы с адресами — текст сайта (там бывают «программы обучения»), смотрим только наши пояснения
    txt = re.sub(r"<script.*?</script>|<style.*?</style>|<tbody>.*?</tbody>", " ", doc, flags=re.S)
    txt = re.sub(r"<[^>]+>", " ", txt)
    out = []
    for m in re.finditer(r"рограмм|\.csv\b|Обновить отчёт|SiteAnalyzer|Screaming|ИНСТРУКЦИЯ|запустите|в окне", txt):
        around = txt[max(0, m.start() - 60):m.end() + 40]
        if m.group() == "рограмм" and any(w in around for w in OK_WORDS):
            continue
        out.append(re.sub(r"\s+", " ", around))
    return out


def _inline_images(doc, out_dir):
    """Снимки телефона (мобильная/01.jpg) и снимки с обведённой ошибкой — внутрь файла, чтобы клиенту хватило
    одного HTML."""
    def sub(m):
        p = os.path.join(out_dir, m.group(1), os.path.basename(m.group(2)))
        if not os.path.exists(p):
            return m.group(0)
        ext = os.path.splitext(p)[1].lower().lstrip(".")
        with open(p, "rb") as f:
            return 'src="data:image/%s;base64,%s"' % ("jpeg" if ext in ("jpg", "jpeg") else ext,
                                                      base64.b64encode(f.read()).decode())
    return re.sub(r'src="(мобильная|снимки ошибок|снимки кнопок|снимки согласия)/([^"]+)"', sub, doc)


def write(out_dir, meta, issues, pages, summary):
    path = os.path.join(out_dir, FILE)
    tmp = path + ".tmp"
    html_report(tmp, meta, [i for i in issues if i.key not in HIDE], pages, summary, client=True)
    with open(tmp, encoding="utf-8") as f:
        doc = f.read()
    os.remove(tmp)
    for a, b in REPLACE:
        doc = doc.replace(a, b)
    doc = re.sub(r'<p class="mut">Не всё загрузилось: .*?</p>', "", doc)  # технические ошибки загрузки данных
    doc = _inline_images(doc, out_dir)
    with open(path, "w", encoding="utf-8") as f:
        f.write(doc)
    return path
