DEFAULTS = {"ignore": IGNORE, "synonyms": SYNONYMS, "info": INFO, "gallery": GALLERY, "axes": AXES, "brands": BRANDS}


def _clean(lines):
    out, seen = [], set()
    for s in lines:
        s = re.sub(r"\s+", " ", str(s).replace("\r", "")).strip()
        if not s:
            continue
        key = s.lower().replace("ё", "е")
        if key not in seen:
            seen.add(key)
            out.append(s)
    return out[:MAX_LINES]


def load():
    """Все словари строками (как на странице), со строками «# …»."""
    try:
        with open(FILE, encoding="utf-8") as f:
            d = json.load(f)
    except (OSError, ValueError):
        d = {}
    return {k: _clean(d[k]) if isinstance(d.get(k), list) else list(DEFAULTS[k]) for k in KINDS}


def save(kind, lines):
    if kind not in KINDS:
        raise ValueError("нет такого словаря")
    d = load()
    d[kind] = _clean(lines)
    jsonfile.save(FILE, d, indent=1)
    return d


def reset(kind):
    return save(kind, DEFAULTS[kind])


def norm(s):
    s = s.lower().replace("ё", "е")
    s = re.sub(r"[^\w\s\-]", " ", s)
    return re.sub(r"\s+", " ", s).strip()


def active(lines):
    return [norm(s) for s in lines if not s.lstrip().startswith("#") and norm(s)]


class Markers:
    """Поиск маркеров (слов и фраз) в запросе. Слова сравниваются точно, без основы: по основе «читать» совпало
    с городом «Чита», «лично» с «личный кабинет». Поэтому в словаре пишутся все нужные формы («инструкция»,
    «инструкции»), как в списке по умолчанию."""
    def __init__(self, lines):
        self.items = []
        for m in active(lines):
            ws = m.replace("-", " ").split()
            if ws:
                self.items.append((m, tuple(ws)))

    def find(self, q):
        ws = tuple(norm(q).replace("-", " ").split())
        for m, mk in self.items:
            n = len(mk)
            if any(ws[i:i + n] == mk for i in range(len(ws) - n + 1)):
                return m
        return None


BUY_RX = re.compile(r"(?<![а-я])(купить|куплю|цена|цены|ценой|стоимость|заказать|недорого|дешево|прайс|магазин\w*|"
                    r"в наличии|доставк\w*)(?![а-я])")


def intent_of(q, d=None):
    """«info», «gallery» или None. Маркеры статей важнее галереи: «как выглядит котел фото» - вопрос.
    Если в запросе есть «купить», «цена», «заказать», маркер не считается: «газовые колонки какую лучше купить»,
    «котлы цены и фото» - это покупка (на gasprofservice.ru таких 16 из 1 200 запросов с маркерами)."""
    d = d or load()
    if BUY_RX.search(norm(q)):
        return None, None
    m = Markers(d["info"]).find(q)
    if m:
        return "info", m
    m = Markers(d["gallery"]).find(q)
    if m:
        return "gallery", m
    return None, None
