STOP_FILE = paths.data("стоп-слова.json")


def load_stop():
    try:
        with open(STOP_FILE, encoding="utf-8") as f:
            return sorted({str(w).strip().lower() for w in json.load(f) if str(w).strip()})
    except Exception:
        return []


def save_stop(words):
    words = sorted({str(w).strip().lower().replace("ё", "е") for w in words if str(w).strip()})[:2000]
    jsonfile.save(STOP_FILE, words, indent=0)
    return words
