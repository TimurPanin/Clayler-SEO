def canon_city(name):
    """«Питер», «СПб», «Мск», «Подмосковье» - другие имена большого города: «Санкт-Петербург», «Москва».
    Без этого у сайта из Петербурга запрос «шкафы спб» отсеивался как «другой город: СПб»."""
    return CITY_ALIASES.get((name or "").lower(), name)


def city_by_name(name):
    for c in CITIES:
        if c[0].lower() == name.lower() or c[1].lower() == name.lower():
            return next(x for x in CITIES if x[0] == canon_city(c[0]))
    return None


