def own_names(host):
    """Как могут искать сам сайт: имя домена (gasprofservice) и его звучание (газпрофсервис)."""
    from .stem import sound
    label = (host or "").lower().removeprefix("www.").split(".")[0]
    if len(label) < 4:
        return set()
    return {label, _own_sound(label)}


def _own_sound(w):
    """Звучание для сравнения с названием сайта: service = сервис (c перед e/i - «с», конечная «е» не слышна)."""
    from .stem import sound
    return sound(re.sub(r"c(?=[eiy])", "s", w.lower())).rstrip("e")


def refine_intent(q, intent, names=()):
    """Намерение с учётом «Сравнения» и «Навигации»: только для «Информации» и «Общего» (покупка и услуга важнее)."""
    if intent not in ("Информация", "Общий"):
        return intent
    if names:
        if any(t in names or _own_sound(t) in names for t in re.findall(r"[a-zа-я0-9-]+", q.lower().replace("ё", "е"))
               if len(t) >= 4):
            return "Навигация"
    for name, rx in INTENT_FIRST:
        # «импульсный режим работы кофемолки что это» - вопрос, а не поиск адреса
        if rx.search(q) and not (name == "Навигация" and QUESTION_NAV.search(q)):
            return name
    return intent


def refine_intents(data):
    """Семантика, собранная до 10.10.2026, - те же намерения при чтении (export.load), без нового сбора."""
    names = own_names(data.get("host"))
    for g in data.get("groups") or []:
        for r in g.get("q") or []:
            if len(r) > 2:
                r[2] = refine_intent(r[0], r[2], names)
    return data

