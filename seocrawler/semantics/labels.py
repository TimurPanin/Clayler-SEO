"""Одни и те же слова для видов групп и страниц семантики везде: окно («Семантика», плитки, вкладки), отчёт для
клиента, Excel, Telegram, дерево сайта, структура нового сайта. Название меняется только здесь; окно берёт слова
из /api/semantics (поле labels). тест/проверить_слова.py ловит старые варианты в коде.

Как писать число: «126 групп: есть на сайте» (плитки) или «Есть на сайте: 126 групп» (строки текста) - count()."""

# вид группы (export.PRIO_KIND): короткое название и пояснение
KIND = {
    "page": ("Есть на сайте", "страница под эти запросы на сайте есть, её продвигать"),
    "create": ("Создать", "спрос есть, а подходящей страницы на сайте нет"),
    "absent": ("Решить, нужна ли", "на сайте нет ни страницы, ни товаров: решить, нужна ли такая страница"),
    "manual": ("Разобрать вручную", "запросы не подошли ни к одной группе"),
}
# страница группы после сверки (plan.status): «есть на сайте» делится на подходит / доработать / не та страница
STATUS = {
    "ok": ("Подходит", "страница есть и подходит: поддерживать и развивать"),
    "fix": ("Доработать", "страница есть, но запросы раскрыты слабо"),
    "wrong": ("Не та страница", "страница не про это: выбрать подходящую или создать новую"),
    "create": KIND["create"], "absent": KIND["absent"], "manual": KIND["manual"],
}
# дерево сайта и структура нового сайта: цвет строки
TREE = {"have": KIND["page"][0], "filter": "Фильтр есть на сайте", "create": KIND["create"][0],
        "decide": KIND["absent"][0]}
# в конце пояснения «что делать» у группы без страницы
DECIDE = "решить, нужна ли страница"

UNITS = {"group": ("группа", "группы", "групп"), "page": ("страница", "страницы", "страниц"),
         "filter": ("страница-фильтр", "страницы-фильтра", "страниц-фильтров"),
         "query": ("запрос", "запроса", "запросов"), "brand": ("бренд", "бренда", "брендов")}


def plural(n, unit="group"):
    a, b, c = UNITS[unit]
    n = abs(int(n or 0)) % 100
    m = n % 10
    return c if 10 < n < 20 else b if 1 < m < 5 else a if m == 1 else c


def label(key):
    for d in (STATUS, KIND):
        if key in d:
            return d[key][0]
    return TREE[key]


def tile(key, n, unit="group"):
    """Подпись под числом в плитке: «групп: есть на сайте»."""
    return f"{plural(n, unit)}: {label(key)[:1].lower() + label(key)[1:]}"


def count(key, n, unit="group"):
    """Строка текста: «Есть на сайте: 126 групп» (число - с пробелами)."""
    from ..fmt import num
    return f"{label(key)}: {num(n)} {plural(n, unit)}"


def for_js():
    return {"kind": {k: list(v) for k, v in KIND.items()}, "status": {k: list(v) for k, v in STATUS.items()},
            "tree": TREE}
