"""Мобильная версия: отдаёт ли сайт телефону то же, что компьютеру, и правильно ли сделан отдельный m.сайт (версия 6.8)."""
from ..common import MOBILE_HEAVY_MB, NOTE, WARN


def run(ctx):
    add = ctx.add
    md = ctx.store.get_meta("mobile_diff", None) or {}
    if md.get("diffs"):
        vary = (f" На {md['no_vary']} из этих страниц сервер не присылает заголовок «Vary: User-Agent» - без него "
                "кеш провайдера или CDN может показать компьютерную версию телефону и наоборот."
                if md.get("no_vary") else "")
        add("mobile_diff", WARN, "Мобильная версия", "Телефону сайт отдаёт не то, что компьютеру",
            f"Программа открыла {md['checked']} страниц трижды: как Chrome на компьютере, как Chrome на телефоне и снова "
            "как компьютер. Здесь оба ответа компьютеру совпали, а телефону пришло другое. Google и Яндекс оценивают "
            "сайт по мобильной версии: если на телефоне нет заголовка, текста или ссылок, в поиске их тоже не будет."
            + vary,
            "Сверьте колонку «Телефону» с тем, что должно быть на странице. Если на телефоне пропал текст, H1, ссылки "
            "или поменялся canonical - передайте разработчику: мобильная версия должна содержать то же самое, "
            "только в другой вёрстке.",
            ["Страница", "Что отличается", "Компьютеру", "Телефону"],
            [[d["url"], d["field"], d["desktop"] if d["desktop"] != "" else "(нет)",
              d["phone"] if d["phone"] != "" else "(нет)"] for d in md["diffs"]], page_col=None)
    bad = [x for x in md.get("msite", []) if x["problems"]]
    if bad:
        add("msite_bad", WARN, "Мобильная версия", "Отдельная мобильная версия (m.сайт) связана с основной неправильно",
            "Телефон перенаправляется на другой адрес - отдельную мобильную версию. Поисковик считает её той же "
            "страницей, только если связь прописана с двух сторон: на основной странице - <link rel=\"alternate\" "
            "media=\"only screen and (max-width: 640px)\"> на мобильный адрес, на мобильной - canonical на основной. "
            "И телефон должен попадать на ту же страницу, а не на главную. Иначе это дубли, и в выдачу может попасть "
            "не та версия.",
            "Передайте разработчику: прописать alternate и canonical, как в колонке «Что не так». Надёжнее - "
            "перейти на адаптивную вёрстку (один адрес для всех устройств), так советуют Google и Яндекс.",
            ["Страница", "Адрес для телефона", "Что не так"],
            [[x["url"], x["mobile"], "; ".join(x["problems"])] for x in bad], page_col=None)

    # как страницы выглядят на телефоне (встроенный браузер, 375 px) — выборочно
    mv = ctx.store.get_meta("mobile_view", None)
    if not mv or not mv.get("pages"):
        return
    from ...mobile_view import WIDTH, load_seconds
    rows = [r for r in mv["pages"] if not r.get("error")]
    n = len(rows)
    intro = f"Программа открыла {n} страниц в браузере шириной {WIDTH} px, как на телефоне. "
    wide = [r for r in rows if max(r.get("sw", 0), r.get("vw", 0)) > WIDTH + 1]
    add("mobile_wide", WARN, "Мобильная версия", "На телефоне страница шире экрана",
        intro + "На этих страницах что-то не помещается по ширине: телефон либо показывает горизонтальную прокрутку, "
        "либо уменьшает всю страницу, и текст становится мелким. Google и Яндекс считают такие страницы неудобными "
        "для телефона. Снимки - в разделе «Как сайт выглядит на телефоне».",
        "Передайте разработчику колонку «Что вылезает за край»: этим блокам нужна ширина не больше 100% экрана "
        "(max-width: 100%, перенос строк, у таблиц - прокрутка внутри блока).",
        ["Страница", "Ширина страницы, px", "Что вылезает за край"],
        [[r["url"], max(r.get("sw", 0), r.get("vw", 0)),
          "нет meta viewport (см. проблему выше)" if r.get("viewport") is False
          else ", ".join(r.get("over") or []) or "не определилось"]
         for r in wide], page_col=None)
    small = [r for r in rows if r.get("text_total") and r.get("text_small", 0) / r["text_total"] > 0.4]
    add("mobile_small_text", WARN, "Мобильная версия", "Мелкий текст на телефоне",
        intro + "Больше 40% текста на этих страницах написано шрифтом мельче 12 px - на телефоне его трудно читать "
        "без увеличения. Такое же правило у Google Lighthouse.",
        "Передайте разработчику: основной текст на телефоне - не меньше 16 px, мелкие подписи - не меньше 12 px.",
        ["Страница", "Мелкого текста", "Примеры"],
        [[r["url"], f"{100 * r['text_small'] // r['text_total']}%", "; ".join(r.get("small_ex") or [])] for r in small],
        page_col=None)
    taps = [r for r in rows if r.get("taps")]
    add("mobile_taps", NOTE, "Мобильная версия", "Маленькие кнопки и ссылки вплотную друг к другу",
        intro + "Здесь есть кнопки или ссылки меньше 24×24 px, стоящие так близко к соседним, что пальцем легко нажать "
        "не то. Ссылки внутри текста не считаются. Минимум 24×24 px - по стандарту доступности WCAG 2.2, "
        "Google советует 48×48 px.",
        "Передайте разработчику: увеличить высоту строк меню и ссылок в подвале (padding) или расстояние между ними.",
        ["Страница", "Сколько", "Примеры (ширина×высота, px)"],
        [[r["url"], r["taps"], "; ".join(r.get("tap_ex") or [])] for r in taps], page_col=None)
    heavy = sorted([r for r in rows if r.get("bytes", 0) > MOBILE_HEAVY_MB * 1048576], key=lambda r: -r["bytes"])
    add("mobile_heavy", WARN, "Мобильная версия", f"На телефоне страница весит больше {MOBILE_HEAVY_MB} МБ",
        intro + "Здесь посчитано всё, что браузер телефона скачал при первом открытии страницы: картинки, скрипты, "
        "шрифты, счётчики, виджеты, в том числе то, что догрузили сами скрипты. На мобильном интернете такая страница "
        "открывается долго и тратит трафик посетителя. Время - оценка по весу для медленного 4G (1,6 Мбит/с).",
        "Начните с самого тяжёлого в колонке «Из них картинки»: сжать картинки, перевести в WebP, отдавать телефону "
        "картинки его размера (srcset), картинкам ниже первого экрана - loading=\"lazy\".",
        ["Страница", "МБ", "Из них картинки, МБ", "Скрипты, МБ", "Запросов", "Секунд на медленном 4G"],
        [[r["url"], round(r["bytes"] / 1048576, 1), round(r.get("by_type", {}).get("картинки", 0) / 1048576, 1),
          round(r.get("by_type", {}).get("скрипты", 0) / 1048576, 1), r.get("requests", 0),
          round(load_seconds(r["bytes"]))] for r in heavy], page_col=None)
