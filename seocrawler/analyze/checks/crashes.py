"""Сбои самой программы (не ошибки сайта)."""
from ..common import FAULTS, NOTE, _q


def run(ctx):
    add, db = ctx.add, ctx.db
    fails = _q(db, "SELECT url, skip_reason FROM urls WHERE skip_reason LIKE 'Сбой обработки%'")
    add("program_fail", NOTE, "Программа", "Страницы, которые программа не смогла разобрать",
        "Это не ошибка сайта, а сбой программы при разборе страницы: такие адреса выпали из остальных проверок "
        "или проверены не полностью. "
        "Подробности - в файле «сбои.txt» в папке проверки.",
        "Передайте файл «сбои.txt» тому, кто сопровождает программу. Страницы из списка проверьте вручную.",
        ["Адрес", "Сбой"], [[r["url"], r["skip_reason"]] for r in fails], page_col=None)


def data_faults(ctx):
    """Запускается последней (analyze._analyze): испорченные данные встречают все проверки."""
    ctx.add("data_fault", NOTE, "Программа", "Данные, которые не прочитались при анализе",
            "Это не ошибка сайта: часть сохранённых данных проверки испорчена или часть анализа не сработала. Эти "
            "страницы "
            "могли не попасть в отдельные проверки отчёта.",
            "Передайте список тому, кто сопровождает программу. Если данные испорчены, поможет новая проверка сайта.",
            ["Что", "Сколько", "Например", "Ошибка"], [[k, len(v[0]), v[1], v[2]] for k, v in sorted(FAULTS.items())],
            page_col=None)
