"""Водность и тошнота своего текста страниц (seocrawler/textstat.py).

Считается по абзацам своего текста: без шаблона сайта (меню, шапка, подвал, повторяющиеся блоки) и без коротких
строк - названий товаров, цен, кнопок. Абзац - блок от PARA_MIN_WORDS слов, где есть конец предложения.
Иначе в каталоге «тошнило» бы от названий товаров («Celtic-DS Platinum» 150 раз), а это не текст."""
import re

from ...fmt import num
from ...textstat import fmt, stats, top_text
from ..common import NOTE, WARN, own_blocks
from ... import settings as S

PARA_MIN_WORDS = 8
_SENT = re.compile(r"[а-яёa-z)»\"][.!?…](\s|$)", re.I)


def paragraphs(blocks):
    """Абзацы текста из блоков страницы: от PARA_MIN_WORDS слов и с концом предложения."""
    return " ".join(b for b in blocks if len(b.split()) >= PARA_MIN_WORDS and _SENT.search(b))


def classic_max(words):
    """Порог классической тошноты для текста из words слов. Она растёт с длиной текста: в статье на 5 000 слов
    главное слово 80 раз - это 1,6%, не переспам. У длинного текста порог - пока самое частое слово не больше 2,5%
    (hightime.agency, 23.10.2026: тексты на 2-5,5 тыс. слов с академической 5-9% попадали в «тошноту»)."""
    return max(S.NAUSEA_MAX, (words * 0.025) ** 0.5)


def run(ctx):
    add, indexable, pages = ctx.add, ctx.indexable, ctx.pages
    own = getattr(ctx, "own_blocks", None)
    if own is None:
        own = own_blocks(indexable)
    if not own:
        return  # старая проверка без блоков текста: посчитать не по чему
    by_url = {}
    for p in indexable:
        if p["url"] in own:
            st = stats(paragraphs(own[p["url"]]), S.TEXT_STATS_MIN_WORDS)
            if st:
                by_url[p["url"]] = st
    # свой текст страниц больше никому не нужен: на большом сайте это гигабайты (thehome.ru 01.11.2026: 3 ГБ),
    # которые иначе держались бы до конца анализа
    ctx.own_blocks = own = None
    for p in pages:
        st = by_url.get(p["url"])
        if st:
            p["water"], p["nausea"], p["nausea_acad"] = st["water"], st["classic"], st["academic"]
    ctx.text_stats = by_url
    lim = (f"больше {S.WATER_MAX}%")
    water = sorted(([u, st["words"], fmt(st["water"]) + "%", ", ".join(st["water_words"])]
                    for u, st in by_url.items() if st["water"] > S.WATER_MAX), key=lambda r: -float(r[2][:-1].replace(",", ".")))
    add("text_water", NOTE, "Контент", f"Много «воды» в тексте ({lim} пустых слов)",
        "«Вода» - слова, которые не несут смысла: местоимения, частицы, вводные слова и общие фразы («конечно», "
        "«является», «данный», «очень»). У живого текста обычно 10-20%. Чем больше воды, тем меньше в тексте "
        "сути: людям скучно читать, а поисковику труднее понять, о чём страница. Считается по абзацам своего текста "
        f"страницы (без меню и подвала), у текстов от {S.TEXT_STATS_MIN_WORDS} слов.",
        "Сократите общие фразы и вводные слова, замените их фактами: цены, сроки, размеры, примеры. "
        "Сначала - важные страницы: услуги, категории, статьи.",
        ["Адрес", "Слов в тексте", "Вода", "Чаще всего"], water)
    nausea = sorted(([u, st["words"], fmt(st["classic"]), fmt(st["academic"]) + "%", top_text(st)]
                     for u, st in by_url.items()
                     if st["classic"] > classic_max(st["words"]) or st["academic"] > S.NAUSEA_ACAD_MAX),
                    key=lambda r: -float(r[3][:-1].replace(",", ".")))
    add("text_nausea", WARN, "Контент",
        f"Слова повторяются слишком часто (тошнота больше {fmt(S.NAUSEA_MAX)}, у длинных текстов - выше, "
        f"или академическая больше "
        f"{fmt(S.NAUSEA_ACAD_MAX)}%)",
        "Тошнота показывает, как часто в тексте повторяются одни и те же слова. Классическая - корень из числа "
        "повторов самого частого слова (разные формы слова считаются одним), академическая - какую долю текста "
        "занимают самые частые слова. Переспамленный текст неприятно читать, а Яндекс и Google понижают такие "
        "страницы в поиске (у Яндекса это фильтр «Баден-Баден»). Считается по абзацам своего текста страницы, "
        "без меню, подвала, названий товаров и цен. Классическая тошнота растёт с длиной текста, поэтому у текстов "
        f"длиннее {num(round(S.NAUSEA_MAX ** 2 / 0.025))} слов порог выше: самое частое слово занимает больше 2,5% текста.",
        "Уберите лишние повторы слов из колонки «Чаще всего»: замените их синонимами, местоимениями или просто "
        "удалите. Ключевую фразу достаточно употребить несколько раз - в заголовке, в начале текста и по смыслу дальше.",
        ["Адрес", "Слов в тексте", "Тошнота", "Академическая", "Чаще всего"], nausea)
