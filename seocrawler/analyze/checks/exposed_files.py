        "Скрыть версии в настройках сервера (nginx - «server_tokens off», PHP - «expose_php = Off») и убрать "
        "мета-тег generator из кода страниц, если он есть. Если PHP устарел - обновить его у хостинга (сначала "
        "проверить сайт на копии).",
