"""Несуществующая страница, срок сертификата (версия 6) и срок оплаты домена."""
import datetime as dt

from ..common import CERT_CRIT_DAYS, CERT_WARN_DAYS, CRIT, DOMAIN_CRIT_DAYS, DOMAIN_WARN_DAYS, NOTE, WARN


def run(ctx):
    store = ctx.store
    add = ctx.add
    f404 = store.get_meta("fake404", None)
    if f404 and f404.get("chain"):
        ch = f404["chain"]
        first, last = ch[0][1], ch[-1]
        path = "\n→ ".join(f"{u} ({c})" for u, c in ch)
        if first == 200 or (isinstance(last[1], int) and last[1] == 200):
            what = ("открывается с кодом 200" if first == 200 else "перенаправляет на рабочую страницу")
            add("fake404", CRIT, "Коды ответа", "Несуществующая страница не отдаёт ошибку 404",
                "Программа открыла заведомо несуществующий адрес, и он " + what + ". Значит, любой мусорный "
                "или опечатанный адрес для поисковика - рабочая страница: в индекс попадают пустышки и дубли, "
                "а битые ссылки невозможно найти.",
                "Передайте разработчику: несуществующие адреса должны отвечать кодом 404 (страница «не найдено» "
                "может быть красивой, но код ответа - 404).",
                ["Проверочный адрес", "Что ответил сервер"], [[f404["url"], path]], page_col=None)
    add("any_url_home", CRIT, "Коды ответа", "Сайт на любой адрес отдаёт главную страницу",
        "Адреса из ссылок и меню, а также заведомо несуществующий адрес отвечают кодом 200 и показывают то же самое, "
        "что и главная. Своих разделов по этим адресам не видят ни посетитель, ни поисковик, а любой адрес становится "
        "копией главной. Так бывает, например, когда адрес страницы не доходит до движка сайта (часто после переезда "
        "на другой сервер), но точную причину видно только в настройках сервера.",
        "Передайте разработчику: проверить, как сервер передаёт адрес страницы в движок сайта (правила перезаписи "
        "адресов), и добиться, чтобы разделы открывались, а несуществующие адреса отвечали 404. Находки про одинаковый "
        "текст, title и описание на этих адресах - следствие этой ошибки.",
        ["Адрес", "Ссылок на него", "Где стоит ссылка"],
        [[u, len(ctx.inl.get(u, ())), ctx.src_of(u, 2)] for u in sorted(ctx.home_copies)],
        page_col=None)
    c304 = store.get_meta("check304", None)
    if c304 and (c304.get("last_modified") or c304.get("etag")) and c304.get("status") == 200:
        add("no_304", NOTE, "Яндекс", "Сервер не отвечает «не изменилось» (304)",
            "Сервер сообщает дату изменения страницы (Last-Modified) или её отпечаток (ETag), но на повторный запрос "
            "«изменилась ли страница с этой даты?» всё равно отдаёт её целиком (код 200). Яндекс рекомендует отвечать "
            "304 - тогда робот не перекачивает неизменённые страницы и быстрее находит новые.",
            "Передайте разработчику: включить поддержку If-Modified-Since / If-None-Match (в Битриксе - настройка "
            "«Выдавать 304» или модуль композита; на nginx - для статики работает само).",
            ["Адрес", "Last-Modified", "ETag", "Ответ на повторный запрос"],
            [[c304["url"], c304.get("last_modified", ""), c304.get("etag", ""), c304["status"]]], page_col=None)
    cert = store.get_meta("cert", None)
    if cert and cert.get("days_left") is not None and cert["days_left"] < CERT_WARN_DAYS:
        d = cert["days_left"]
        add("cert_expiry", CRIT if d < CERT_CRIT_DAYS else WARN, "Безопасность",
            ("Сертификат HTTPS уже истёк" if d < 0 else f"Сертификат HTTPS истекает через {d} дн."),
            "Когда сертификат истечёт, браузеры покажут посетителям «Подключение не защищено», "
            "а поисковики перестанут нормально обходить сайт.",
            "Передайте хостингу или разработчику: продлить сертификат (Let's Encrypt продлевается автоматически, "
            "если это настроено: проверьте настройку).",
            ["Домен", "Действует до", "Осталось дней"], [[cert["host"], cert["not_after"], d]], page_col=None)
    # домен: срок оплаты из whois/RDAP (site_tech). Истечёт - не откроется весь сайт и почта, поэтому за месяц - критично
    dom = (store.get_meta("site_tech", None) or {}).get("domain") or {}
    try:
        left = (dt.date.fromisoformat(dom.get("expires") or "") - dt.date.today()).days
    except ValueError:
        left = None
    if left is not None and left < DOMAIN_WARN_DAYS:
        add("domain_expiry", CRIT if left < DOMAIN_CRIT_DAYS else WARN, "Безопасность",
            ("Оплата домена уже закончилась" if left < 0 else f"Оплата домена заканчивается через {left} дн."),
            "Когда оплата домена закончится, сайт и почта на этом домене перестанут работать, сайт выпадет из поиска, "
            "а домен через некоторое время смогут купить другие. Часто домен продлевается автоматически - но это "
            "надо проверить, а не предполагать.",
            "Проверьте срок в личном кабинете регистратора" + (f" ({dom['registrar']})" if dom.get("registrar") else "")
            + " и продлите домен (лучше сразу на несколько лет и с автопродлением). Если уже продлили - "
            "сведения в реестре обновляются в течение суток.",
            ["Домен", "Оплачен до", "Осталось дней", "Регистратор"],
            [[dom.get("domain") or "", dom.get("expires"), left, dom.get("registrar") or ""]], page_col=None)

