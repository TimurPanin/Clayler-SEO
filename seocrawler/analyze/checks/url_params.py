"""Адреса и метки."""
from ..common import NOTE, WARN, _q, defaultdict, urlsplit


def run(ctx):
    add, db, html_ok = ctx.add, ctx.db, ctx.html_ok
    pl = _q(db, "SELECT DISTINCT src, raw, removed FROM param_links")
    add("tracking_links", WARN, "Адреса", "Внутренние ссылки с метками (utm, id сессии и т. п.)",
        "Ссылки внутри сайта содержат рекламные метки или служебные параметры. Для поисковика адрес с меткой - "
        "отдельная страница, то есть дубль. Метки нужны только в рекламе и рассылках, а не в ссылках на своём сайте.",
        "Уберите метки из внутренних ссылок. Программа сама обходила адрес без меток, чтобы не плодить дубли.",
        ["Страница со ссылкой", "Ссылка", "Лишние параметры"], [[r["src"], r["raw"], r["removed"]] for r in pl])
    # Каждый адрес — только то, что может порождать дубли. Подчёркивания и длина — это стиль адресов всего сайта:
    # одной строкой-сводкой, а не тысячами строк (менять адреса работающих страниц ради этого не нужно).
    url_rows, style = [], defaultdict(list)
    for p in html_ok:
        path = urlsplit(p["url"]).path
        probs = []
        if any(c.isupper() for c in path):
            probs.append("заглавные буквы")
        if "%" in path:
            probs.append("русские буквы или пробелы")
        if "//" in path:
            probs.append("двойной слеш")
        if probs:
            url_rows.append([p["url"], ", ".join(probs)])
        if "_" in path:
            style["подчёркивание «_» вместо дефиса «-»"].append(p["url"])
        if len(p["url"]) > 115:
            style["адрес длиннее 115 символов"].append(p["url"])
    add("url_issues", NOTE, "Адреса", "Адреса с заглавными или русскими буквами, двойным слешем",
        "Заглавные буквы и двойные слеши в адресах часто рождают дубли (/Page и /page - разные адреса), "
        "а русские буквы превращаются в длинные коды %D0%BA…, когда ссылкой делятся.",
        "Не ошибка. Менять адреса у работающих страниц стоит только вместе с 301-редиректом со старого адреса.",
        ["Адрес", "Что заметно"], url_rows, page_col=None)
    add("url_style", NOTE, "Адреса", "Стиль адресов сайта (сводка)",
        "Google советует разделять слова в адресах дефисом, а не подчёркиванием, и не делать адреса слишком "
        "длинными. Это рекомендации для новых страниц, а не ошибки: на позиции существующих страниц влияет слабо.",
        "Менять адреса работающих страниц ради этого не нужно. Для новых разделов - дефисы и короткие адреса.",
        ["Что заметно", "Сколько страниц", "Примеры"],
        [[k, len(v), "\n".join(v[:3])] for k, v in style.items()], page_col=None)

    if any(p["url"].startswith("https://") for p in html_ok):
        mixed = _q(db, """SELECT DISTINCT src, dst, kind FROM links WHERE internal=1 AND kind='a'
                          AND src LIKE 'https://%' AND dst LIKE 'http://%'""")
        add("http_links", WARN, "Безопасность", "Ссылки на свой сайт через http:// вместо https://",
            "Сайт работает на https, но часть ссылок ведёт на http-версию. Каждый такой клик проходит через лишний "
            "редирект. Картинки и скрипты по http - в разделе «Смешанный контент».",
            "Замените в ссылках http:// на https://.",
            ["Страница со ссылкой", "Ссылка"], [[r["src"], r["dst"]] for r in mixed])

