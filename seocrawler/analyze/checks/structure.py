"""Структура."""
from ..common import DEEP_CLICKS, NOTE, WARN


def run(ctx):
    add, indexable, inl, src_of = ctx.add, ctx.indexable, ctx.inl, ctx.src_of
    add("deep", WARN, "Структура", f"Страницы дальше {DEEP_CLICKS} кликов от главной",
        "Чтобы добраться до этих страниц, нужно сделать больше трёх переходов с главной. Такие страницы "
        "робот обходит реже, и внутренних ссылок на них мало.",
        "Поставьте на важные страницы ссылки ближе к главной: в меню, в разделы, в блоки «популярное».",
        ["Адрес", "Кликов от главной"], [[p["url"], p["depth"]] for p in indexable if (p["depth"] or 0) > DEEP_CLICKS],
        page_col=None)  # это про структуру сайта, а не про саму страницу — на здоровье не влияет
    add("one_inlink", NOTE, "Структура", "Страницы, на которые ведёт всего одна ссылка",
        "Эти страницы почти не связаны с остальным сайтом: на каждую ведёт ссылка только с одной страницы.",
        "Для важных страниц добавьте ссылки из похожих разделов.",
        ["Адрес", "Откуда ссылка"], [[p["url"], src_of(p["url"])] for p in indexable
                                     if len(inl.get(p["url"], ())) == 1 and p["depth"]], page_col=None)

