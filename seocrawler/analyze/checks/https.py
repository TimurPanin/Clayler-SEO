"""SSL."""
from ..common import CRIT, NOTE, defaultdict, urlsplit


def run(ctx):
    add, all_checked, src_of = ctx.add, ctx.all_checked, ctx.src_of
    ssl_int = [r for r in all_checked if r["internal"] and r["ssl_note"]]
    if ssl_int:
        hosts = defaultdict(list)
        for r in ssl_int:
            hosts[urlsplit(r["url"]).hostname].append(r["url"])
        add("ssl_own", CRIT, "Безопасность", "Сертификат HTTPS вашего сайта не прошёл проверку",
            "Сайт открывается, но проверка сертификата не прошла. Браузеры в таком случае показывают "
            "посетителям предупреждение «Подключение не защищено». Частая причина - сертификат истёк "
            "или на сервере не установлен промежуточный сертификат.",
            "Откройте сайт в браузере и нажмите на замок в адресной строке. Если предупреждения нет, "
            "скорее всего, на сервере не хватает промежуточного сертификата (браузер докачивает его сам, "
            "а поисковые роботы и другие программы - нет). Передайте хостингу или разработчику.",
            ["Сайт", "Страниц", "Пример"], [[h, len(u), u[0]] for h, u in hosts.items()], page_col=None)
    ssl_ext = [r for r in all_checked if not r["internal"] and r["ssl_note"]]
    add("ssl_ext", NOTE, "Безопасность", "Чужие сайты с сертификатом, который не прошёл проверку",
        "Эти сайты открылись, но их HTTPS-сертификат программа проверить не смогла. Часто это ложная тревога: "
        "например, сертификат выдан российским удостоверяющим центром, которому доверяет не каждая программа.",
        "Откройте ссылку в браузере. Если браузер не ругается, всё в порядке, ничего делать не нужно.",
        ["Внешний адрес", "Код", "Где стоит ссылка"],
        [[r["url"], r["status"], src_of(r["url"], 2)] for r in ssl_ext], page_col=None)

