"""Орфографические ошибки в тексте страниц (Яндекс.Спеллер, результат в meta «spelling»)."""
import re
import zlib

from ...speller import unquoted
from ..common import NOTE, defaultdict

_WORD = re.compile(r"[а-яё]+", re.I)
# Слова, которых нет в словаре Спеллера, но они правильные: профессиональные слова маркетинга, IT и торговли и
# обычные формы, которые он не знает (ниша → «нишам»). Основа слова - ловит все формы. Не список под один сайт:
# так пишут на любом сайте агентства, магазина или сервиса (primerline.agency: 20 из 45 «ошибок» - такие)
JARGON = re.compile(
    r"^(?:маркетплейс|ретаргетинг|ремаркетинг|видеоразбор|видеоинструкц|видеоурок|ревью|блогер|блогинг|влог|"
    r"аутстафф?|аутсорс|чеклист|чек-лист|лендинг|таргетинг|таргетирован|таргет|лидоген|линкбилдинг|перелинковк|сниппет|юзабилити|дашборд|"
    r"фриланс|коворкинг|стартап|онбординг|апсейл|кросселл|кросс-?сейл|нетворкинг|воронк|продакт|самореференс|"
    r"транскреац|околоцелев|гиков|гик|таск|карьерно|нишам|нишах|нишами|инфлюенс|инфлюэнс|креатив|брендинг|"
    r"ребрендинг|копирайт|рерайт|медиапл|фичи|фичу|фича|бэклог|бэклинк|спринт|скоуп|дедлайн|апдейт|хостинг|"
    r"парсинг|парсер|скрипт|кликабельн|конверсионн|омниканальн|мультиканальн|сео|смм|серм|тренинг|вебинар|"
    r"подкаст|лонгрид|сторителлинг|геймификац|диджитал|эдтех|финтех|фудтех|ритейл|e-?ком|дропшип|фулфилмент|"
    r"селлер|байер|мерч|кешбэк|кэшбэк|промокод|ретеншн|лояльност|юнит|когорт|атрибуц|бенчмарк|аудит)"
    # после основы - только окончание (гласные, й, ь, м, х, в, г): «аудитт», «скриптт» - опечатки, их не прячем
    r"[аеёиоуыэюяйьмхвг]{0,4}$", re.I)


def run(ctx):
    add, store, indexable = ctx.add, ctx.store, ctx.indexable
    sp = store.get_meta("spelling", None) or {}
    errors = {w: s for w, s in (sp.get("errors") or {}).items() if not JARGON.match(w)}
    if not errors:
        return
    where, torn = defaultdict(list), {}
    for p in indexable:
        b = p.get("blocks")
        if not b:
            continue
        try:
            # слово только в коротких кавычках - цитата или пример, а не опечатка (и для старых проверок)
            text = unquoted(zlib.decompress(b).decode("utf-8"))
        except Exception:
            continue
        for w in set(_WORD.findall(text)) & errors.keys():
            where[w].append(p["url"])
            # «протестиро-вано»: Спеллер видит обрывок, а на сайте лишний дефис посреди слова - так и показываем
            m = w not in torn and re.search(rf"\b{w}-([а-яё]+)\b", text)
            if m:
                # вопросом: «лидген-агентство» - правильное составное слово
                torn[w] = (f"{w}-{m.group(1)}", f"дефис посреди слова? Если да - {w}{m.group(1)}")
    rows = sorted(([torn.get(w, (w,))[0], torn[w][1] if w in torn else ", ".join(errors[w]), len(u),
                    "\n".join(sorted(u)[:3])] for w, u in where.items()), key=lambda r: (-r[2], r[0]))
    add("spelling", NOTE, "Контент", "Орфографические ошибки в тексте",
        "Яндекс.Спеллер нашёл слова, похожие на опечатки. Ошибки в тексте снижают доверие посетителей, а поисковик "
        "может не связать страницу с запросом, написанным правильно. Слово на многих страницах - оно в меню, "
        "шапке или подвале: исправляется один раз в шаблоне.",
        "Проверьте список: исправьте настоящие ошибки. Названия брендов, моделей и профессиональные слова "
        "Спеллер иногда считает ошибками - такие строки пропустите (или выключите проверку в «Пороги и проверки»).",
        ["Слово", "Может быть", "На скольких страницах", "Например, здесь"], rows, page_col=None)
