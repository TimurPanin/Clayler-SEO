"""Счётчики посещаемости (версия 7.1): на каждой ли странице стоит Яндекс Метрика и Google Analytics.
Страница без счётчика — посещения на ней не считаются: отчёты Метрики врут, цели не срабатывают.
Старые проверки счётчики не собирали (колонка counters пустая) — для них проверки нет."""
import json

from ..common import NOTE, WARN, defaultdict

NAMES = {"ym": "Яндекс Метрики", "ga": "Google Analytics"}


def run(ctx):
    add = ctx.add
    seen = []
    for p in ctx.html_ok:
        c = p.get("counters")
        if c is None:
            continue
        try:
            seen.append((p, json.loads(c)))
        except ValueError:
            continue
    if len(seen) < 3:
        return
    for key, name in NAMES.items():
        have = [p for p, c in seen if c.get(key)]
        miss = [p for p, c in seen if not c.get(key)]
        if not have or not miss:
            continue
        # счётчик стоит на большинстве страниц — значит, на остальных его забыли (часто: отдельный шаблон)
        if len(have) >= 0.5 * len(seen):
            add(f"counter_{key}_missing", WARN if key == "ym" else NOTE, "Аналитика",
                f"Нет счётчика {name} на части страниц",
                f"Счётчик {name} есть на {len(have)} из {len(seen)} страниц, а на этих - нет. Посещения этих страниц "
                f"не попадают в отчёты, цели и электронная коммерция на них не работают, а данные о трафике из поиска "
                f"по ним занижены. Обычно у таких страниц свой шаблон (карточка товара, статьи, лендинг).",
                "Передайте разработчику: подключить тот же код счётчика в шаблон этих страниц. Проверить после "
                "правки - «Поиск по сайту» → «Страницы без счётчика» в окне программы.",
                ["Адрес", "Title"], [[p["url"], p.get("title") or ""] for p in miss])
    # Несколько разных счётчиков Метрики: данные делятся между ними, каждый показывает часть посещений
    ids = defaultdict(list)
    for p, c in seen:
        for i in c.get("ym") or []:
            if i != "?":
                ids[i].append(p["url"])
    if len(ids) > 1:
        rows = [[i, len(urls), "\n".join(urls[:2])] for i, urls in sorted(ids.items(), key=lambda kv: -len(kv[1]))]
        # Счётчик «везде» — на 90% страниц со счётчиками. Два таких — это просто два счётчика на каждой странице
        # (свой и подрядчика): данные не делятся. Делятся — когда у части страниц свой, отдельный номер.
        everywhere = [i for i, urls in ids.items() if len(urls) >= 0.9 * len(seen)]
        partial = [i for i in ids if i not in everywhere]
        if partial:
            add("counter_ym_many", NOTE, "Аналитика", "На части страниц другой счётчик Метрики",
                "У большинства страниц один номер счётчика, а у этих - другой (или ещё один). Посещения таких страниц "
                "видны только в «их» счётчике: в отчётах основного они пропадают, путь посетителя рвётся. Иногда это "
                "осознанно (лендинг подрядчика) - тогда всё в порядке.",
                "Проверьте, какой счётчик основной (номер - в Метрике), и поставьте его и на эти страницы.",
                ["Номер счётчика", "На скольких страницах", "Например"], rows, page_col=None)
        elif len(everywhere) > 1:
            add("counter_ym_many", NOTE, "Аналитика", "На каждой странице несколько счётчиков Метрики",
                "На всех страницах стоит больше одного счётчика Метрики. Данные не теряются, но каждый счётчик - лишний "
                "скрипт: страница грузится дольше. Часто один из них - старый или подрядчика, к которому уже нет доступа.",
                "Проверьте в Метрике, какими счётчиками вы пользуетесь, и уберите ненужные.",
                ["Номер счётчика", "На скольких страницах", "Например"], rows, page_col=None)
    if not any(c.get("ym") or c.get("ga") or c.get("gtm") for _p, c in seen):
        add("counter_none", NOTE, "Аналитика", "На сайте не найден счётчик посещаемости",
            "Ни на одной странице нет кода Яндекс Метрики, Google Analytics или Google Tag Manager. Без счётчика не видно, "
            "сколько людей приходит из поиска, на какие страницы и что они делают. Счётчик может подключаться необычно "
            "(через сторонний скрипт) - тогда программа его не узнаёт; проверьте в Метрике.",
            "Установите Яндекс Метрику (бесплатно, metrika.yandex.ru) на все страницы сайта.",
            ["Пример страницы"], [[p["url"]] for p, _c in seen[:5]], page_col=None)
