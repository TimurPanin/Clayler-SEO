"""Устойчивость к дублям (версия 6)."""
from ..common import NOTE, WARN


def run(ctx):
    store = ctx.store
    add = ctx.add
    dv = store.get_meta("dup_variants", None)
    if dv:
        bad = [x for x in dv if x["verdict"] == "bad"]
        tested = len({x["url"] for x in dv})
        main_bad = [x for x in bad if x["kind"] != "лишний параметр"]
        param_bad = [x for x in bad if x["kind"] == "лишний параметр"]
        kinds = sorted({x["kind"] for x in main_bad})
        add("dup_variants", WARN, "Дубли", "Испорченный адрес открывает ту же страницу (дубль)",
            f"Программа взяла {tested} рабочих страниц и открыла их адреса с изменениями: заглавные буквы, двойной слеш, "
            "слеш в конце или без него, index.php. Правильно - редирект 301 на настоящий адрес, ошибка 404 или canonical "
            "на настоящий адрес. Здесь «испорченный» адрес открывается как отдельная страница - поисковик может "
            "найти его по чужой ссылке или опечатке и получить дубль."
            + (f" Не справляются варианты: {', '.join(kinds)}." if kinds else ""),
            "Передайте разработчику: для таких адресов настроить 301 на правильный адрес (или 404), либо везде выводить "
            "canonical на правильный адрес. Это правило сервера или шаблона - исправляется один раз.",
            ["Настоящий адрес", "Вариант", "Как изменён", "Что ответил сайт"],
            [[x["url"], x["variant"], x["kind"], x["detail"]] for x in main_bad], page_col=None)
        add("dup_params", NOTE, "Дубли", "Адрес с лишним параметром открывается без canonical",
            "К адресу страницы дописан несуществующий параметр (?clayler=1), и сайт открыл страницу без canonical на "
            "настоящий адрес. Так появляются дубли из ссылок с метками и параметрами. Яндекс это частично решает "
            "директивой Clean-param в robots.txt, Google - canonical.",
            "Выводите canonical на адрес без параметров на всех страницах; для Яндекса - Clean-param для служебных "
            "параметров (utm и т. п.).",
            ["Настоящий адрес", "Вариант", "Что ответил сайт"],
            [[x["url"], x["variant"], x["detail"]] for x in param_bad], page_col=None)

