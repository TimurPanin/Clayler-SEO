"""Редиректы."""
from ...robots import CLOSED_LIKE
from ..common import CRIT, NOTE, WARN, _q
from .codes import bucket, not_open


def run(ctx):
    add, code, db, inl = ctx.add, ctx.code, ctx.db, ctx.inl
    pages, redir, rtype = ctx.pages, ctx.redir, ctx.rtype
    seen = {}
    closed = {r[0]
              for r in db.execute("SELECT url FROM urls WHERE state='skipped' AND skip_reason LIKE ?", (CLOSED_LIKE,))}

    def end_code(u):
        """Что в конце редиректа: код, а если конец закрыт в robots.txt - и это (код дочитан при сборке, reread)."""
        end = follow(u)[0][-1]
        return f"{code(end)}, закрыт в robots.txt" if end in closed else code(end)

    def follow(u):
        """ctx.follow с запоминанием: одну цепочку проходят списки редиректов, «ведёт на ошибку» и «ссылки на адреса с
        редиректом» - на большом сайте по нескольку раз на строку."""
        if u not in seen:
            seen[u] = ctx.follow(u)
        return seen[u]
    int_redirects = [p for p in pages if p["url"] in redir]
    add("redirects", NOTE, "Редиректы", "Адреса, которые перенаправляют на другие",
        "Сам по себе редирект - нормальная вещь (например, после переезда страницы). Здесь просто список для справки.",
        "Ничего делать не нужно, если редиректы задуманы. Но внутренние ссылки лучше вести сразу на конечный адрес - "
        "см. «Ссылки на адреса с редиректом».",
        ["Адрес", "Тип", "Куда ведёт", "Код в конце", "Ссылок на него"],
        [[p["url"], rtype.get(p["url"], ""), redir[p["url"]], end_code(p["url"]), len(inl.get(p["url"], ()))]
         for p in int_redirects],
        page_col=None)
    chains, loops = [], []
    for p in int_redirects:
        ch, loop = follow(p["url"])
        if loop:
            loops.append([p["url"], "\n→ ".join(ch)])
        elif len(ch) > 2:
            chains.append([p["url"], len(ch) - 1, "\n→ ".join(ch), code(ch[-1])])
    add("redirect_loops", CRIT, "Редиректы", "Редиректы по кругу",
        "Адрес перенаправляет на другой, а тот - обратно. Страница не откроется ни у посетителя, ни у робота.",
        "Передайте разработчику: один из редиректов в цикле лишний.",
        ["Адрес", "Цикл"], loops)

    # 301/302/... без заголовка Location: «переехала», а куда - не сказано. Раньше такой адрес не попадал ни в один
    # пункт (в списке редиректов только адреса с Location). Коды ответа по порядку
    # все свои адреса (и файлы), а не только страницы: ящик тот же, что в codes.bucket (закон сохранения)
    noloc = [r for r in ctx.all_checked if r["internal"] and r["kind"] != "sitemap"
             and bucket(r["status"], r["error"], r["location"]) == "redirect_noloc"]
    add("redirect_noloc", CRIT, "Редиректы", "Редирект без адреса: страница не открывается",
        "Сервер отвечает «страница переехала», но не говорит куда (нет адреса перехода - заголовка Location). "
        "Браузер показывает пустую страницу или ошибку, робот дальше не идёт.",
        "Передайте разработчику: указать адрес, куда ведёт редирект, или убрать редирект, если страница на месте.",
        ["Адрес", "Код", "Ссылок на него", "Где стоят ссылки"],
        [[r["url"], r["status"], len(inl.get(r["url"], ())), ctx.src_of(r["url"])] for r in noloc])

    # редирект, который заканчивается ошибкой: «Ссылки на адреса с редиректом» советовали поставить в ссылку его конец -
    # то есть страницу 404
    # Что такое «не открывается» - общее правило codes.not_open, без своего списка кодов: ошибка 4xx/5xx, нет ответа
    # или обрывок (у кода 200 с ошибкой пишется текст ошибки, а не «200»), редирект без адреса. 429/408 и не
    # проверенный конец (tg://) - не ошибка.
    ends = {}

    def bad_end(u):
        """Код или текст ошибки в конце цепочки редиректов, если там не открывается; иначе None."""
        if u not in ends:
            ch, loop = follow(u)
            ends[u] = None
            if not loop and ch[-1] in ctx.status:
                st, err = ctx.status[ch[-1]]
                if not_open(st, err, redir.get(ch[-1], "")):
                    ends[u] = (err or "нет ответа") if bucket(st, err, "?") == "noresp" else st
        return ends[u]

    # все свои адреса с редиректом, и файлы тоже: на них отсылают «Ссылки на адреса с редиректом»
    own_redir = [r["url"] for r in ctx.all_checked if r["internal"] and r["kind"] != "sitemap" and r["url"] in redir]
    to_err = [[u, follow(u)[0][-1], bad_end(u), len(inl.get(u, ()))] for u in own_redir if bad_end(u)]
    add("redirect_to_error", CRIT, "Редиректы", "Редирект ведёт на ошибку",
        "Адрес перенаправляет на страницу, которая не открывается (404, ошибка сервера). Посетитель после перехода "
        "видит ошибку, а вес ссылок на старый адрес пропадает.",
        "Перенаправьте на рабочую страницу, близкую по смыслу. Если такой нет - уберите редирект, и пусть старый адрес "
        "сам отвечает 404 или 410, а ссылки на него уберите.",
        ["Адрес", "Куда ведёт в итоге", "Код в конце", "Ссылок на него"], to_err, page_col=None)

    # конец редиректа закрыт в robots.txt, а сам открывается (или не ответил): робот не пройдёт по такому редиректу.
    # Закон сохранения: конец редиректа - рабочий, с ошибкой или закрытый, а не «ничего не сказали» (dom-primer.ru
    #)
    to_closed = [[u, follow(u)[0][-1], code(follow(u)[0][-1]), len(inl.get(u, ()))] for u in own_redir
                 if follow(u)[0][-1] in closed and not follow(u)[1] and not bad_end(u)]
    add("redirect_to_blocked", WARN, "Редиректы", "Редирект ведёт на страницу, закрытую в robots.txt",
        "Адрес перенаправляет на страницу, куда сайт запрещает заходить поисковым роботам. Робот по такому редиректу "
        "не пройдёт: новая страница не попадёт в поиск через этот переход. Посетитель её при этом видит.",
        "Если страница нужна в поиске, откройте её в robots.txt или перенаправьте на открытую страницу с тем же "
        "содержимым. Если не нужна, поставьте редирект на близкий по смыслу раздел.",
        ["Адрес", "Куда ведёт в итоге", "Код в конце", "Ссылок на него"], to_closed, page_col=None)

    temp = [p for p in int_redirects if p["status"] in (302, 303, 307)]
    add("redirect_temp", NOTE, "Редиректы", "Временные редиректы (302, 303, 307)",
        "Временный редирект говорит поисковику: «страница скоро вернётся». Поисковик может оставить в выдаче старый "
        "адрес и не передать новому вес ссылок. Для входа в личный кабинет, корзины или выбора города временный "
        "редирект - нормально.",
        "Если страница переехала навсегда - передайте разработчику: заменить на постоянный редирект 301.",
        ["Адрес", "Код", "Куда ведёт", "Код в конце", "Ссылок на него"],
        [[p["url"], p["status"], redir[p["url"]], end_code(p["url"]), len(inl.get(p["url"], ()))] for p in temp],
        page_col=None)
    https_downgrade = [c for c in chains if "http://" in c[2] and c[0].startswith("https://")]
    add("redirect_chains", WARN, "Редиректы", "Цепочки редиректов (несколько переходов подряд)",
        "Чтобы открыть страницу, браузер и робот проходят несколько перенаправлений. Это замедляет загрузку, "
        "а на каждом шаге может теряться вес ссылки."
        + (" Особенно плохо, если цепочка проходит через http:// - посетителя на один шаг уводит "
           "с защищённого соединения." if https_downgrade else ""),
        "Настройте на сервере так, чтобы старый адрес сразу вёл на конечный, одним редиректом."
        + (" Обычно причина - правило «добавить слеш в конце», которое строит адрес с http:// "
           "вместо https://." if https_downgrade else ""),
        ["Начальный адрес", "Переходов", "Цепочка", "Итог"], chains)

    ltr = _q(db, """SELECT l.dst, COUNT(DISTINCT l.src) AS n, MIN(l.src) AS ex, MAX(l.anchor) AS anchor
        FROM links l JOIN urls u ON u.url=l.dst
        WHERE l.kind='a' AND u.internal=1 AND l.dst IN (SELECT url FROM pages WHERE location IS NOT NULL AND location<>'')
        GROUP BY l.dst ORDER BY n DESC""")
    add("links_to_redirect", WARN, "Редиректы", "Ссылки на адреса с редиректом",
        "На сайте стоят ссылки на адреса, которые сразу перенаправляют дальше. Каждый клик - лишний переход. "
        "Если такая ссылка есть в меню или подвале, она повторяется на всех страницах.",
        "Замените в ссылке адрес на конечный (колонка «Правильный адрес»). "
        "Ссылки из меню и подвала исправляются один раз в шаблоне сайта.",
        ["Адрес в ссылке", "Правильный адрес", "Текст ссылки", "На скольких страницах", "Например, здесь"],
        [[r["dst"], "редирект по кругу - см. «Редиректы по кругу»" if follow(r["dst"])[1] else
          f"нет: ведёт на ошибку ({bad_end(r['dst'])}) - см. «Редирект ведёт на ошибку»" if bad_end(r["dst"]) else
          follow(r["dst"])[0][-1], r["anchor"], r["n"], r["ex"]] for r in ltr], page_col=None)

