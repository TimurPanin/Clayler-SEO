"""Роботу и браузеру отдаётся разное (версия 6)."""
from ..common import WARN


def run(ctx):
    store = ctx.store
    add = ctx.add
    ud = store.get_meta("ua_diff", None)
    if ud and ud.get("diffs"):
        add("ua_diff", WARN, "Индексация", "Роботу и браузеру сайт отдаёт разное",
            f"Программа открыла {ud['checked']} страниц трижды: как робот, как браузер Chrome и снова как робот. "
            "Здесь оба ответа роботу совпали между собой, а браузеру пришло другое - значит, это не случайность, "
            "а сайт (кеш сервера, прокси, защита от ботов) отдаёт роботам другую версию. Поисковик видит то, что в колонке "
            "«Роботу». Если там ошибка (внутренний адрес, другой canonical, noindex) - в поиске будет она.",
            "Передайте разработчику или хостингу: выяснить, почему роботу приходит другое (настройки кеша, прокси, "
            "защиты от ботов). Проверить можно в Яндекс Вебмастере («Проверка ответа сервера») и Search Console "
            "(«Проверка URL»).",
            ["Страница", "Что отличается", "Роботу", "Браузеру"],
            [[d["url"], d["field"], d["bot"], d["browser"]] for d in ud["diffs"]], page_col=None)

