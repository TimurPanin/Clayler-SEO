"""Автотест «Разложить новые запросы по группам» и словарей (semantics/assign.py, semantics/dicts.py): запрос идёт
в группу по общим словам; редкое главное слово важнее частого («термопара для газового котла» - в «Термопары»);
синонимы «айфон = iphone»; маркеры статей и галереи; «купить» отменяет маркер; рискованные слова выключены;
«уже в группе», «не подошло»; свой файл «Группа + Запрос»; словари сохраняются и возвращаются как было.
Словари и раскладка пишутся во временную папку, настоящие файлы не трогаются."""
import io
import os
import sys
import tempfile

TMP = tempfile.mkdtemp(prefix="clayler-sort-")
os.environ["CLAYLER_DECISIONS_DIR"] = os.path.join(TMP, "решения")
os.environ["CLAYLER_DICTS_FILE"] = os.path.join(TMP, "словари.json")
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from openpyxl import Workbook, load_workbook  # noqa: E402
from seocrawler.semantics import assign as A, dicts as DI  # noqa: E402

fails = []


def check(ok, what):
    if not ok:
        fails.append(what)


G = [("Газовые котлы", ["газовые котлы", "газовый котел купить", "газовые котлы двухконтурные", "котел газовый настенный",
                        "газовые котлы для отопления частного дома", "газовый котел цена"]),
     ("Термопары", ["термопара", "термопара для газового котла", "термопара для колонки", "термопара купить",
                    "термопара для котла аогв"]),
     ("Электрические котлы", ["электрические котлы", "электрический котел для отопления", "электрокотел купить",
                              "электрические котлы цена"]),
     ("Apple iPhone", ["iphone 15", "купить iphone 14", "iphone 13 цена", "iphone 15 pro"]),
     ("Счетчики воды", ["счетчики воды", "счетчик воды купить", "счетчик горячей воды", "счетчики для воды"])]
NEW = ["газовый котел навьен 24 квт", "термопара для газового котла аристон", "электрокотлы для дома",
       "айфон 15 про макс", "как выбрать газовый котел", "газовые котлы фото", "газовые котлы какой лучше купить",
       "счетчик воды ширина 110", "газовые котлы", "велосипед детский", "котел газовый своими руками"]
res = {r["q"]: r for r in A.run(G, [{"q": q} for q in NEW])}
want = {"газовый котел навьен 24 квт": "Газовые котлы", "термопара для газового котла аристон": "Термопары",
        "айфон 15 про макс": "Apple iPhone", "как выбрать газовый котел": A.ARTICLES, "газовые котлы фото": A.GALLERY,
        "газовые котлы какой лучше купить": "Газовые котлы", "счетчик воды ширина 110": "Счетчики воды",
        "велосипед детский": A.NONE, "котел газовый своими руками": A.ARTICLES}
for q, g in want.items():
    check(res[q]["group"] == g, f"«{q}»: {res[q]['group']} ({res[q]['how']}), ждали {g}")
check(res["газовые котлы"]["how"] == "уже в группе", f"дубль: {res['газовые котлы']}")
check(res["как выбрать газовый котел"]["topic"] == "Газовые котлы", f"тема статьи: {res['как выбрать газовый котел']}")
check(res["газовый котел навьен 24 квт"]["why"], "нет общих слов в пояснении")

# маркеры: точное слово (не «Чита» от «читать»), рискованные выключены, фразы
check(DI.intent_of("водонагреватели чита")[0] is None, "«чита» сработала как «читать»")
check(DI.intent_of("кран шаровой гост")[0] is None, "«гост» включён по умолчанию")
check(DI.intent_of("бытовая техника")[0] is None, "«техника» включена по умолчанию")
check(DI.intent_of("что такое термопара") == ("info", "что"), f"что такое: {DI.intent_of('что такое термопара')}")
check(DI.intent_of("примеры работ фото")[0] == "info", "маркер статьи важнее галереи")
check(DI.intent_of("котлы цены и фото")[0] is None, "«цены» не отменили маркер")

# словари: сохранить, выключить синоним, вернуть как было
DI.save("synonyms", ["# айфон = iphone"])
r = A.run(G, [{"q": "айфон 15 про макс"}])[0]
check(r["group"] != "Apple iPhone", f"выключенный синоним сработал: {r}")
DI.save("info", DI.load()["info"] + ["подобрать"])
check(DI.intent_of("подобрать котел")[0] == "info", "своё слово в маркерах не сработало")
DI.reset("synonyms")
DI.reset("info")
check(DI.load()["synonyms"] == DI.SYNONYMS and DI.intent_of("подобрать котел")[0] is None, "«Вернуть как было» не вернуло")

# свой файл с группами (Key Collector: «Группа», «Фраза», «Частота») и новые запросы из файла
wb = Workbook()
ws = wb.active
ws.append(["Группа", "Фраза", "Частота"])
for name, qs in G:
    for q in qs:
        ws.append([name, q, 10])
b = io.BytesIO()
wb.save(b)
groups = A.groups_from_file("группы.xlsx", b.getvalue())
check(len(groups) == 5 and dict(groups)["Термопары"][0] == "термопара", f"файл с группами: {groups[:2]}")
new = A.new_from("термопара для колонки нева\t90\nгазовые котлы бакси", "", b"")
check(new[0] == {"q": "термопара для колонки нева", "freq": 90} and len(new) == 2, f"вставленный список: {new}")
d = A.save("test.ru", A.run(groups, new), "из файла")
check(A.load("test.ru")["rows"][0]["group"] == "Термопары", "раскладка не сохранилась")
path = os.path.join(TMP, "р.xlsx")
A.write_xlsx(path, d, "test.ru")
ws = load_workbook(path).active
check(ws["A1"].value == "Запрос" and ws.max_row == 3, f"Excel: {ws['A1'].value}, строк {ws.max_row}")

if fails:
    print("✗ раскладка по группам:\n   " + "\n   ".join(fails))
    sys.exit(1)
print("✓ раскладка по группам: общие слова, синонимы, маркеры статей и галереи, свой файл с группами, словари, Excel")
